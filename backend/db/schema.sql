-- Redaktionelles Schema der Klima-App (PostgreSQL 16 + PostGIS)

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TYPE difficulty       AS ENUM ('leicht', 'mittel', 'schwer');
CREATE TYPE warning_severity AS ENUM ('low', 'medium', 'high');

-- ---------------------------------------------------------------- Lookups

CREATE TABLE walk_categories (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key  text     NOT NULL UNIQUE,   -- mappt auf frontend/src/assets/icons/<key>.svg
    name text     NOT NULL,
    sort smallint NOT NULL DEFAULT 0
);

CREATE TABLE target_audiences (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key  text     NOT NULL UNIQUE,
    name text     NOT NULL,
    sort smallint NOT NULL DEFAULT 0
);

CREATE TABLE poi_types (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key  text     NOT NULL UNIQUE,
    name text     NOT NULL,
    icon text,                       -- mappt auf frontend/src/assets/icons/poi-*.svg
    sort smallint NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------- Inhalte

-- body/action_body: Blockliste [{ type: 'heading'|'text'|'image', … }], s. ArticleBody.vue
CREATE TABLE topics (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label            text NOT NULL,
    name             text NOT NULL,
    summary          text,
    body             jsonb,
    thumbnail_url    text,
    action_title     text,
    action_body      jsonb,
    action_image_url text,
    featured         boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE walk_locations (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL,
    name              text NOT NULL,
    short_text        text,
    body              jsonb,
    thumbnail_url     text,
    aerial_url        text,
    location          geometry(Point, 4326),
    station_number    integer UNIQUE,   -- sichtbare "Standort N"-Nummer, unabhängig vom PK
    address           text,
    in_klima_quartett boolean NOT NULL DEFAULT false,
    featured          boolean NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE routes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label         text NOT NULL,
    name          text NOT NULL,
    short_text    text,
    body          jsonb,
    thumbnail_url text,
    distance_km   real,
    duration_min  integer,
    route_points  geometry(LineString, 4326),
    category_id   smallint REFERENCES walk_categories(id),
    difficulty    difficulty,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- Junctions
-- Einzelspalten-PK, weil Directus keine zusammengesetzten PKs unterstützt;
-- die fachliche Eindeutigkeit trägt jeweils das UNIQUE.

CREATE TABLE route_stops (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id    integer NOT NULL REFERENCES routes(id)         ON DELETE CASCADE,
    stop_index  integer NOT NULL,
    location_id integer NOT NULL REFERENCES walk_locations(id) ON DELETE CASCADE,
    UNIQUE (route_id, location_id)
);

CREATE TABLE route_target_audiences (
    id          integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id    integer  NOT NULL REFERENCES routes(id)           ON DELETE CASCADE,
    audience_id smallint NOT NULL REFERENCES target_audiences(id) ON DELETE CASCADE,
    UNIQUE (route_id, audience_id)
);

-- ---------------------------------------------------------------- POIs

CREATE TABLE pois (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id     smallint NOT NULL REFERENCES poi_types(id),
    name        text NOT NULL,
    description text,
    image_url   text,
    address     text,
    geom        geometry(Geometry, 4326) NOT NULL,   -- Punkt, Coole-Orte-Bereiche als Polygon
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pois_geom_type CHECK (GeometryType(geom) IN ('POINT', 'POLYGON', 'MULTIPOLYGON'))
);

-- ---------------------------------------------------------------- Warnungen

CREATE TABLE warnings (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       text NOT NULL,
    description text,
    severity    warning_severity NOT NULL DEFAULT 'medium',
    action_icon text,
    action_text text,
    help        jsonb,             -- { heading, tel, text }
    valid_from  timestamptz,
    valid_to    timestamptz,       -- NULL = unbegrenzt
    active      boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE warning_tips (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warning_id integer NOT NULL REFERENCES warnings(id) ON DELETE CASCADE,
    sort       smallint NOT NULL DEFAULT 0,
    heading    text NOT NULL,
    text       text NOT NULL,
    icon       text
);

-- ---------------------------------------------------------------- Indizes

CREATE INDEX walk_locations_location_idx ON walk_locations USING gist (location);
CREATE INDEX routes_route_points_idx     ON routes         USING gist (route_points);
CREATE INDEX pois_geom_idx               ON pois           USING gist (geom);
CREATE INDEX pois_type_idx               ON pois (type_id);
CREATE INDEX route_stops_route_order_idx ON route_stops (route_id, stop_index);
